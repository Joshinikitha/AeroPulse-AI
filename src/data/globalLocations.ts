// Helper to convert GlobalCityPoint to AirMonitoringStation for Leaflet compatibility
export function toAirMonitoringStation(point: GlobalCityPoint): AirMonitoringStation {
  return {
    id: point.id,
    stationName: point.stationName || `${point.city} Station`,
    city: point.city,
    district: point.district || point.city,
    state: point.state || point.country,
    country: point.country,
    latitude: point.lat,
    longitude: point.lon,
    aqi: point.aqi,
    dominantPollutant: point.dominantPollutant as any,
    category: point.category as any,
    pollutants: {
      pm25: point.pm25,
      pm10: point.pm10,
      no2: point.no2,
      so2: point.so2,
      co: point.co,
      o3: point.o3,
    },
    weather: {
      temperature: point.temperature ?? 25,
      humidity: point.humidity ?? 60,
      windSpeed: point.windSpeed ?? 10,
    },
    stationType: 'Continuous Ambient CAAQMS',
    operatingAgency: point.operatingAgency || 'National Air Quality Service',
    lastUpdated: point.lastUpdated || new Date().toISOString(),
    source: (point.source as any) || 'waqi-live',
  };
}
